/* ---------- Modal de confirmación reutilizable ---------- */
function confirmar(opciones) {
  const opts = Object.assign({
    titulo: '¿Está seguro?',
    mensaje: '',
    confirmarTexto: 'Confirmar',
    cancelarTexto: 'Cancelar',
    tipo: 'primary',
    onConfirmar: function () {},
  }, opciones);

  const modal = document.createElement('div');
  modal.className = 'modal-backdrop';
  modal.id = 'modalConfirm';
  modal.innerHTML =
    '<div class="modal" style="max-width:400px">' +
    '<div class="modal-header"><h3>' + escapeHtml(opts.titulo) + '</h3>' +
    '<button type="button" class="modal-close" data-confirm-cerrar>&times;</button></div>' +
    '<div class="modal-body"><p style="margin:0;color:var(--text)">' + opts.mensaje + '</p></div>' +
    '<div class="modal-footer">' +
    '<button type="button" class="btn btn-outline" data-confirm-cancelar>' + escapeHtml(opts.cancelarTexto) + '</button>' +
    '<button type="button" class="btn btn-' + opts.tipo + '" data-confirm-aceptar>' + escapeHtml(opts.confirmarTexto) + '</button>' +
    '</div></div>';

  document.body.appendChild(modal);
  requestAnimationFrame(() => modal.classList.add('open'));

  function cerrar() {
    modal.classList.remove('open');
    setTimeout(() => modal.remove(), 200);
  }
  modal.querySelector('[data-confirm-cerrar]').addEventListener('click', cerrar);
  modal.querySelector('[data-confirm-cancelar]').addEventListener('click', cerrar);
  modal.addEventListener('click', (e) => { if (e.target === modal) cerrar(); });
  modal.querySelector('[data-confirm-aceptar]').addEventListener('click', () => {
    cerrar();
    opts.onConfirmar();
  });
}