function showToast(message, type = 'info', duration = 3200) {
  let container = document.querySelector('.toast-container');
  if (!container) {
    container = document.createElement('div');
    container.className = 'toast-container';
    document.body.appendChild(container);
  }
  const toast = document.createElement('div');
  toast.className = 'toast ' + type;
  toast.textContent = message;
  container.appendChild(toast);
  setTimeout(() => {
    toast.classList.add('hiding');
    setTimeout(() => toast.remove(), 350);
  }, duration);
}

function openModal(id) {
  const modal = document.getElementById(id);
  if (modal) modal.classList.add('open');
}

function closeModal(id) {
  const modal = document.getElementById(id);
  if (modal) modal.classList.remove('open');
}

function closeModalFromEvent(e) {
  if (e.target === e.currentTarget) e.currentTarget.classList.remove('open');
}

function escapeHtml(str) {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function validateField(input, testFn, message) {
  const errEl = document.getElementById('err-' + input.id);
  const ok = testFn(input.value);
  input.classList.toggle('is-invalid', !ok);
  if (errEl) {
    errEl.textContent = message;
    errEl.classList.toggle('visible', !ok);
  }
  return ok;
}

/* Escapa valores al rellenar selects/tablas de forma segura */
function opt(name, value, label) {
  return '<option value="' + escapeHtml(value) + '"' + (name === value ? ' selected' : '') + '>' + escapeHtml(label || value) + '</option>';
}

